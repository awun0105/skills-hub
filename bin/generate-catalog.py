#!/usr/bin/env python3
"""Generate CATALOG.md from tracked Git blobs and source locks, not local installs."""
import argparse
from collections import defaultdict
import json
from pathlib import Path, PurePosixPath
import subprocess
from urllib.parse import quote

ROOT = Path(__file__).resolve().parent.parent


def git(*args):
    return subprocess.check_output(['git', '-C', str(ROOT), *args]).decode()


def generate():
    locks = {}
    for line in git('show', ':repos.lock').splitlines():
        if line and not line.startswith('#'):
            path, url, commit = line.split()
            locks[path] = (url.removesuffix('.git'), commit)
    groups = defaultdict(list)
    overlays = set(git('ls-files', '-z', '--', 'overlays').split('\0'))
    entries = git('ls-files', '-s', '-z', '--', 'skills').split('\0')
    local = set()
    for entry in entries:
        if not entry:
            continue
        meta, path = entry.split('\t', 1)
        mode, blob, stage = meta.split()
        if stage != '0':
            raise SystemExit('Resolve Git index conflicts before generating the catalog')
        parts = PurePosixPath(path).parts
        name = parts[1]
        if mode == '120000' and len(parts) == 2:
            target = git('cat-file', '-p', blob)
            dest = PurePosixPath(target)
            if dest.parts[:2] == ('..', 'repos'):
                repo = dest.parts[2]
                url, commit = locks[f'repos/{repo}']
                suffix = '/'.join(dest.parts[3:])
                link = f'{url}/tree/{commit}/{quote(suffix)}'
                overlay = f'overlays/repos/{repo}/{suffix}/SKILL.md'
                if overlay in overlays:
                    link = quote(overlay)
                groups[repo].append((name, link))
            else:
                groups['Hub aliases'].append((name, 'skills/' + quote(target)))
        elif len(parts) == 3 and parts[-1] == 'SKILL.md':
            local.add(name)
    for name in sorted(local):
        groups['Hub-maintained'].append((name, f'skills/{quote(name)}/SKILL.md'))
    lock = json.loads(git('show', ':.skill-lock.json'))
    for name, record in lock['skills'].items():
        groups['npx skills'].append((name, record['sourceUrl'].removesuffix('.git')))
    for path, (url, _) in locks.items():
        if path.startswith('skills/'):
            groups['Standalone repositories'].append((path.split('/')[1], url))
    purposes = {
        'ECC': 'Software engineering, testing, security, and agent operations',
        'scientific-agent-skills': 'Scientific research, data analysis, and domain tools',
        'gsd-core': 'Project planning, execution, and delivery',
        'gstack': 'Product planning, development, design, and QA',
        'claude-mem': 'Agent memory, context, and work handoffs',
        'anthropics-skills': 'Documents, design, communication, and skill authoring',
        'cloudflare-skills': 'Cloudflare applications and infrastructure',
        'superpowers': 'Development workflows, debugging, and verification',
        'OpenSpec': 'Specification-driven change workflows',
        'career-ops': 'Career workflows',
        'claude-task-master': 'Task management',
        'Hub-maintained': 'Local skills and adaptations: thinking, writing, and engineering',
        'Hub aliases': 'Alternate names for hub skills',
        'npx skills': 'Architecture diagrams and database tooling',
        'Standalone repositories': 'Presentation and slide tooling',
    }
    total = sum(map(len, groups.values()))
    lines = [
        '# Skill catalog', '', '[English README](README.md) · [README tiếng Việt](README.vi.md)', '',
        'Generated with `python3 bin/generate-catalog.py`. This lists tracked hub skills and',
        'lock-file installations; machine-only and untracked skills are excluded.',
        'Upstream links use commits from `repos.lock`; npx source links are repository links.',
        'Tracked overlays link to their hub entry points. The root `gstack` skill is generated by upstream setup.',
        'Counts represent installable names, including aliases, rather than unique capabilities.', '',
        f'**{total} skill names across {len(groups)} source groups.**', '',
        'Install the collection with `bin/install.sh` after cloning into `~/.agents`.',
        'For a single npx skill, use `npx skills add <owner>/<repo> --skill <name> -g -y`.', '',
        '| Source group | Focus | Names |', '|---|---|---:|',
    ]
    for group in sorted(groups):
        lines.append(f'| {group} | {purposes[group]} | {len(groups[group])} |')
    for group in sorted(groups):
        lines += ['', '<details>', f'<summary>{group} — {len(groups[group])} names</summary>', '',
                  purposes[group] + '.', '', '| Skill | Source / entry point |', '|---|---|']
        for name, url in sorted(groups[group]):
            lines.append(f'| `{name}` | [{group}]({url}) |')
        lines += ['', '</details>']
    return '\n'.join(lines) + '\n'


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true', help='Fail if the catalog needs regeneration')
    args = parser.parse_args()
    target = ROOT / 'CATALOG.md'
    result = generate()
    if args.check:
        if not target.exists() or target.read_text() != result:
            raise SystemExit('CATALOG.md is stale; run python3 bin/generate-catalog.py')
        print('Catalog is current.')
    else:
        target.write_text(result)
        print(f'Wrote {target}')
